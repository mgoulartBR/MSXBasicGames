def rows(art):
    r = [l for l in art.strip('\n').split('\n')]
    assert len(r) == 16 and all(len(x) == 16 for x in r), "art must be 16x16"
    return r


def sprite_pattern(art):
    r = rows(art)
    bits = [[1 if c != '.' else 0 for c in line] for line in r]
    out = []
    for (x0, y0) in ((0, 0), (0, 8), (8, 0), (8, 8)):   # TL, BL, TR, BR
        for y in range(8):
            v = 0
            for x in range(8): v = (v << 1) | bits[y0 + y][x0 + x]
            out.append(v)
    return out


def px4(line):
    """'...' string of hex pixels -> packed bytes (2 pixels each)"""
    v = [0 if c == '.' else int(c, 16) for c in line]
    return [(v[i] << 4) | v[i + 1] for i in range(0, len(v), 2)]


def db(label, data, per=16):
    out = [f"{label}:"]
    for i in range(0, len(data), per):
        out.append("        db " + ", ".join(f"0x{b:02X}" for b in data[i:i + per]))
    return "\n".join(out)


def main(path):
    pal = []
    for r, g, b in PALETTE: pal += [(r << 4) | b, g]
    spr_pat = sprite_pattern(PLAYER) + sprite_pattern(BULLET)
    player_cols = [13] * 6 + [8] * 6 + [14] * 4
    spr_col = []
    for plane in range(32):
        if plane == 0: spr_col += player_cols
        elif 1 <= plane <= 16: spr_col += [7] * 16
        else: spr_col += [0] * 16
    # sheet: page-1 lines. font at (0,0) 10 glyphs of 8x8, grunt frames at (0,8) and (16,8); records: dw addr16, db addr bit16, db length
    SHEET = 0x18000          # page 3 (line 768 of the 1024-line space)
    lines = []
    for y in range(8):
        data = []
        for ch in "0123456789":
            g = FONT[ch]
            row = g[y] if y < 7 else "....."
            line = ("".join('F' if c == '#' else '.' for c in row) + "...")[:8]
            data += px4(line)
        lines.append((SHEET + y * 128, data))
    for y in range(16):
        data = px4(rows(GRUNT[0])[y]) + px4(rows(GRUNT[1])[y])
        lines.append((SHEET + (8 + y) * 128, data))
    out = ["; generated by tools/msx/gen_gfx.py - do not edit by hand", ""]
    out.append(db("palette", pal)); out.append("")
    out.append(db("spr_pat", spr_pat)); out.append("")
    out.append(db("spr_col", spr_col)); out.append("")
    out.append("sheet_data:")
    for addr, data in lines:
        out.append(f"        dw 0x{addr & 0xFFFF:04X}")
        out.append(f"        db {addr >> 16}, {len(data)}")
        for i in range(0, len(data), 16):
            out.append("        db " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]))
    out.append("        dw 0")
    open(path, 'w').write("\n".join(out) + "\n")
    print(f"{path}: palette {len(pal)}, sprite patterns {len(spr_pat)}, colors {len(spr_col)}, sheet lines {len(lines)}")


if __name__ == '__main__':
    main(sys.argv[1])
