// Generates src/tricks.c: trick-shot layouts that are guaranteed solvable with the game's own physics.
// For every random layout it brute-forces 64 angles x 2 powers and keeps layouts whose number of winning shots is
// inside a window (few = hard).  Build/run:  cc -O2 -I src -o /tmp/trick_gen tools/trick_gen.c src/sp_logic.c && /tmp/trick_gen > src/tricks.c
#include <stdio.h>
#include <stdlib.h>
#include "sp_logic.h"

typedef struct { int cx, cy; int n; int x[4], y[4]; int targets; } Layout;
static const int powers[2] = { 130, 230 };
static unsigned rng = 12345;
static int rnd(int n) { rng = rng * 1103515245u + 12345u; return (int)((rng >> 16) % n); }

static int simulate(const Layout *L, int angle, int power, int *scratch)
{
    SP_Table t; int i, f, mask = 0;
    SP_Clear(&t);
    SP_Place(&t, 0, L->cx, L->cy);
    for (i = 0; i < L->n; i++) SP_Place(&t, i + 1, L->x[i], L->y[i]);
    SP_Sync(&t);
    SP_Shoot(&t, angle, power);
    for (f = 0; f < 900 && SP_Step(&t); f++) ;
    for (i = 0; i < L->n; i++) if (!((t.active >> (i + 1)) & 1)) mask |= 1 << i;
    *scratch = !((t.active >> 0) & 1);
    return mask;
}

static int solutions(const Layout *L, int *best_a, int *best_p)
{
    int a, p, cnt = 0, sc;
    for (a = 0; a < 256; a += 4)
        for (p = 0; p < 2; p++) {
            int m = simulate(L, a, powers[p], &sc);
            if (!sc && (m & L->targets) == L->targets) { if (!cnt) { *best_a = a; *best_p = powers[p]; } cnt++; }
        }
    return cnt;
}

static int free_spot(const Layout *L, int n, int x, int y)
{
    int i, d;
    d = (x - L->cx) * (x - L->cx) + (y - L->cy) * (y - L->cy); if (d < 18 * 18) return 0;
    for (i = 0; i < n; i++) { d = (x - L->x[i]) * (x - L->x[i]) + (y - L->y[i]) * (y - L->y[i]); if (d < 14 * 14) return 0; }
    return 1;
}

int main(void)
{
    // category: number of balls, number of targets, min/max solutions
    static const struct { int balls, targets, lo, hi; } cat[19] = {
        {1,1,10,100},{1,1,8,60},{1,1,6,40},{2,1,5,40},{2,1,4,30},{2,1,3,25},
        {2,2,3,30},{2,2,2,20},{3,1,3,25},{3,2,2,20},{3,2,2,15},{2,2,1,10},
        {3,3,1,12},{3,3,1,8},{4,2,1,12},{4,3,1,8},{4,3,1,6},{4,3,1,5},{4,3,1,3}
    };
    int k;
    printf("// GENERATED by tools/trick_gen.c - trick layouts verified solvable with the game's physics\n#include \"tricks.h\"\n\n");
    printf("const Trick g_Tricks[TRICK_COUNT] = {\n");
    for (k = 0; k < 19; k++) {
        int attempts = 0;
        for (;;) {
            Layout L; attempts++; int i, ok = 1, a = 0, p = 0, s;
            L.n = cat[k].balls; L.targets = (1 << cat[k].targets) - 1;
            L.cx = 40 + rnd(180); L.cy = 40 + rnd(90);
            for (i = 0; i < L.n && ok; i++) {
                int tries = 0;
                do { L.x[i] = 30 + rnd(200); L.y[i] = 36 + rnd(98); tries++; } while (!free_spot(&L, i, L.x[i], L.y[i]) && tries < 50);
                if (tries >= 50) ok = 0;
            }
            if (!ok) continue;
            s = solutions(&L, &a, &p);
            if (s >= 1 && s >= cat[k].lo / (1 + attempts / 80) && s <= cat[k].hi * (1 + attempts / 80)) {
                fprintf(stderr, "trick %d/19 after %d layouts\n", k + 1, attempts);
                printf("\t{ %d, %d, %d, {", L.cx, L.cy, L.n);
                for (i = 0; i < 4; i++) printf("%d%s", i < L.n ? L.x[i] : 0, i < 3 ? "," : "");
                printf("}, {");
                for (i = 0; i < 4; i++) printf("%d%s", i < L.n ? L.y[i] : 0, i < 3 ? "," : "");
                printf("}, %d },   /* %d solutions, e.g. angle %d power %d */\n", L.targets, s, a, p);
                break;
            }
        }
    }
    printf("};\n");
    return 0;
}
