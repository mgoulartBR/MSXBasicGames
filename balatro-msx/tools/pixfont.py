def bitmap(ch, rows=9):
    """-> (width including 1px spacing, rows x width bool grid as lists)"""
    top, lines = GLYPHS[ch]
    w = max(len(l) for l in lines)
    grid = [[False] * (w + 1) for _ in range(rows)]
    for j, l in enumerate(lines):
        for i, c in enumerate(l):
            if c == '#': grid[top + j][i] = True
    return w + 1, grid
