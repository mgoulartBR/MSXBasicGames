"""Cover every modified pixel with at most three background restoration bands."""
from pathlib import Path
import json,re,itertools
root=Path(__file__).resolve().parents[1]
records=[];ids=[];report=[];use_tables=[]
code=(root/'src/combat_assets.c').read_text()
for stage,name in enumerate(['scene','melon']):
 atlas=(root/'assets'/name/'atlas.bin').read_bytes()
 start=code.index('static const SpriteDef sd'+str(stage));block=code[start:code.index(';',start)]
 defs=[list(map(int,v.split(',')))for v in re.findall(r'\{([0-9,]+)\}',block)]
 stageids=[255]*166
 def atlas_pixel(x,y):
  v=atlas[y*128+x//2];return v&15 if x&1 else v>>4
 for frame,sp in enumerate(defs):
  if frame<16 or frame in [30,31] or 36<=frame<46 or 84<=frame<90:continue
  mx,cx,my,cy,w,h,ox,oy=sp
  if not w or not h:continue
  streamed=stage==1 and (108<=frame<116 or 136<=frame<140 or frame in [128,129,134,135])
  if streamed:
   filename,array,index=('aspar_images.h','aspar_images',frame-108)if frame<116 else ('aspar_images.h','mouth_images',frame-136)if frame>=136 else ('tater_images.h','tater_images',frame-128 if frame<130 else frame-132)
   text=(root/'src'/filename).read_text();start=text.index(array+'[');body=text[start:text.index(';',start)]
   data=bytes(map(int,re.findall(r'\{([0-9,]+)\}',body)[index].split(',')))
   assert len(data)==(w//2)*h   # one-pass TIMP rows: 0 transparent, 9 = second black
   def pixel(x,y,color):
    v=data[y*(w//2)+x//2];v=v&15 if x&1 else v>>4
    return (15 if v==0 else 0) if not color else (0 if v in (0,9) else v)
  else:
   # Remaining streamed definitions are not atlas-backed in this stage.
   manifest=json.loads((root/'assets'/name/'combat_assets.json').read_text())['sprites']
   if frame<len(manifest) and any(k.startswith('streamed_')and v for k,v in manifest[frame].items()):continue
   my+=256 if ox&128 else 0;cy+=256 if oy&128 else 0
   def pixel(x,y,color):return atlas_pixel((cx if color else mx)+x,(cy if color else my)+y)
  used=[(x,y)for y in range(h)for x in range(w)if pixel(x,y,0)!=15 or pixel(x,y,1)!=0]
  if not used:continue
  top=min(y for x,y in used);bottom=max(y for x,y in used)+1
  def box(t,b):
   points=[(x,y)for x,y in used if t<=y<b]
   return (min(x for x,y in points),min(y for x,y in points),max(x for x,y in points)+1,max(y for x,y in points)+1)if points else None
  best=[box(top,bottom)];score=lambda v:sum((r-l)*(b-t)+60 for l,t,r,b in v)
  for n in [2,3]:
   for cuts in itertools.combinations(range(top+1,bottom),n-1):
    edges=(top,)+cuts+(bottom,);parts=[box(t,b)for t,b in zip(edges,edges[1:])];parts=[p for p in parts if p]
    if score(parts)<score(best):best=parts
  if score(best)>=w*h+60:continue
  # Include all non-identity mask/color operations, including color index zero.
  assert all(any(l<=x<r and t<=y<b for l,t,r,b in best)for x,y in used)
  def tile_cost(l,t,r,b,wx,wy,parity):
   left=(parity+l)&~1;right=(parity+r+1)&~1
   # World phase corresponds to the unrounded sprite origin.
   left+=wx-parity;right+=wx-parity
   cols=(right-1)//16-left//16+1;rows=(wy+b-1)//16-(wy+t)//16+1
   return (right-left)*(b-t)+cols*rows*100
  bits=[]
  for wy in range(16):
   for wx in range(16):
    for parity in range(2):
     bits.append(int(sum(tile_cost(*box,wx,wy,parity)for box in best)<tile_cost(0,0,w,h,wx,wy,parity)))
  if not any(bits):continue
  use_tables.append([sum(bit<<(j%8)for j,bit in enumerate(bits[k:k+8]))for k in range(0,512,8)])
  stageids[frame]=len(records);records.append(best)
  report.append({'stage':stage,'frame':frame,'original_area':w*h,'bands':best,'covered_area':sum((r-l)*(b-t)for l,t,r,b in best)})
 ids.append(stageids)
assert len(records)<255
s='// Generated by build_restore_bands.py; complete modified-pixel coverage.\n'
s+='static const u8 restore_ids[2][166]={'+','.join('{'+','.join(map(str,v))+'}'for v in ids)+'};\n'
s+='static const u8 restore_bands[][13]={'+','.join('{'+','.join(map(str,[len(v)]+[a for p in v for a in p]+[0]*(12-4*len(v))))+'}'for v in records)+'};\n'
s+='static const u8 restore_use[][64]={'+','.join('{'+','.join(map(str,row))+'}'for row in use_tables)+'};\n'
(root/'src/restore_bands.h').write_text(s)
print(json.dumps(report,indent=2))
