"""Exact partitions for full streamed Mines masks/colors (including black)."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[1]
# Same partition policy as atlas optimization, validated on full runtime rows.
source=(root/'tools/build_fast_enemy.py').read_text()
body=source[source.index('  # Largest all-opaque'):source.index('  # Weighted pixel')]
func='def partition(masks,colors,w,h):\n'+''.join(' '+line[2:]+'\n' for line in body.splitlines())
func=func.replace(' if area<32:continue',' if area<32:return [(0,0,w,h,0)]')+' return parts\n'
exec(func)
records=[];report=[]
for filename,name,w,h in [('aspar_images.h','aspar_images',40,16),('aspar_images.h','mouth_images',32,32),('tater_images.h','tater_images',64,32)]:
 code=(root/'src'/filename).read_text();start=code.index(name+'[');block=code[start:code.index(';',start)]
 arrays=re.findall(r'\{([0-9,]+)\}',block)
 for i,row in enumerate(arrays):
  data=bytes(map(int,row.split(',')));assert len(data)==(w//2)*h
  def pix(x,y):
   v=data[y*(w//2)+x//2];return v&15 if x&1 else v>>4
  # one-pass TIMP images: 0 = transparent, otherwise the colour (9 = the second black); the partition only needs the old
  # mask (15 transparent / 0 opaque) and the old colour (0 under the mask), recovered here.
  masks=[[15 if pix(x,y)==0 else 0 for x in range(w)] for y in range(h)]
  colors=[[0 if pix(x,y) in (0,9) else pix(x,y) for x in range(w)] for y in range(h)]
  parts=partition(masks,colors,w,h);records.append(parts)
  report.append({'array':name,'frame':i,'old_logical_pixels':2*w*h,'parts':parts,'opaque_pixels':sum((r-l)*(b-t) for l,t,r,b,op in parts if op)})
assert len(records)==16
(root/'src/fast_stream_data.h').write_text('// Generated by build_fast_stream.py; all 16 backgrounds checked.\nstatic const u8 stream_parts[16][26]={'+','.join('{'+','.join(map(str,[len(v)]+[n for part in v for n in part]+[0]*(25-5*len(v))))+'}' for v in records)+'};\n')
print(json.dumps(report,indent=2))
