#!/bin/bash
# Real-hardware diagnostic ROMs (ASCII8 + Konami): checks ROM window checksums (per 512-byte block map),
# bank-switch latency, RAM, VRAM read-back and the VBlank hook, and prints a report to photograph.
# Expected values (src/diag_expect.h) are computed from the built ROM image and fed back; iterated until
# stable (segment 6 holds code with absolute addresses).
source "$(dirname "$0")/env.sh"
cd "$RT_ROOT"
gen() { # tag -> writes src/diag_expect.h from dist/...-diag-<tag>.rom + out/republia.map
python3 - "$1" "$VERSION" <<'PY'
import re,sys
tag,ver=sys.argv[1],sys.argv[2]
rom=open(f'dist/republia-msx-{ver}-diag-{tag}.rom','rb').read()
def seg(n): return rom[n*0x2000:(n+1)*0x2000]
m=open('out/republia.map').read()
a=int(re.search(r'\n\s+([0-9A-F]{8})\s+_g_Font_Silk\s',m).group(1),16)&0xFFFF
font=sum(rom[a-0x4000:a-0x4000+95*9])&0xFFFF
o=['// GENERATED by scripts/build_diag.sh - expected ROM contents for the diagnostic build','#pragma once']
for n in (4,5,6): o.append('#define EXP%d %d'%(n,sum(seg(n))&0xFFFF))
o.append('#define EXPF %d'%font)
o.append('static const u16 EXPB[3][16] = {')
for n in (4,5,6):
    s=seg(n); o.append('\t{ '+', '.join(str(sum(s[b*512:(b+1)*512])&0xFFFF) for b in range(16))+' },')
o.append('};')
o.append('static const u8 EXPH[3][16][8] = {')
for n in (4,5,6):
    s=seg(n); o.append('\t{ '+', '.join('{'+','.join(str(x) for x in s[b*512:b*512+8])+'}' for b in range(16))+' },')
o.append('};')
open('src/diag_expect.h','w').write('\n'.join(o)+'\n')
PY
}
for m in ascii8:ROM_ASCII8 konami:ROM_KONAMI; do
  tag=${m%%:*}; mp=${m##*:}
  cp src/diag_expect.h build/diag_expect.prev 2>/dev/null
  for pass in 1 2 3 4 5; do
    RT_DIAG_MODULES=1 RT_MAPPER=$mp RT_TAG=diag-$tag RT_DEFINES="-DRT_DIAG" ./scripts/build.sh >/dev/null 2>&1 || { echo "build failed"; exit 1; }
    cp src/diag_expect.h build/diag_expect.last
    gen $tag
    cmp -s src/diag_expect.h build/diag_expect.last && break
  done
  cmp -s src/diag_expect.h build/diag_expect.last || { echo "expected values did not converge"; exit 1; }
  echo "$tag: converged after $pass passes"
done
ls -l dist/*diag*.rom
